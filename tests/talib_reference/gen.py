"""Regenerates tests/talib_reference/mod.rs: TA-Lib reference values for the
`ta-compat` and f64 fast-path tests.

Needs the TA-Lib Python wrapper (`pip install TA-Lib numpy`). Run from the repo root:

    python tests/talib_reference/gen.py > tests/talib_reference/mod.rs

The input bars come from a fixed-seed random walk with two-decimal prices and
integer volumes, so they convert to `Decimal` exactly.
"""
import random
import sys

import numpy as np
import talib

# LF line endings on every platform (the output is checked in).
sys.stdout.reconfigure(newline=chr(10))

N = 120
rng = random.Random(20261114)
o, h, l, c, v = [], [], [], [], []
price = 100.0
for _ in range(N):
    op = round(price + rng.uniform(-0.6, 0.6), 2)
    cl = round(op + rng.gauss(0, 1.2), 2)
    hi = round(max(op, cl) + rng.uniform(0.0, 1.0), 2)
    lo = round(min(op, cl) - rng.uniform(0.0, 1.0), 2)
    vol = float(rng.randint(1000, 9000))
    o.append(op); h.append(hi); l.append(lo); c.append(cl); v.append(vol)
    price = cl

O, H, L, C, V = (np.array(x, dtype=float) for x in (o, h, l, c, v))


def er(close, n):
    out = np.full(len(close), np.nan)
    for i in range(n, len(close)):
        path = np.sum(np.abs(np.diff(close[i - n:i + 1])))
        out[i] = 0.0 if path == 0 else abs(close[i] - close[i - n]) / path
    return out


def mad(close, n):
    out = np.full(len(close), np.nan)
    for i in range(n - 1, len(close)):
        w = close[i - n + 1:i + 1]
        out[i] = np.mean(np.abs(w - w.mean()))
    return out


series = {}
series["SMA_10"] = talib.SMA(C, 10)
series["EMA_10"] = talib.EMA(C, 10)
series["RSI_14"] = talib.RSI(C, 14)
m, s, hist = talib.MACD(C, 12, 26, 9)
series["MACD_LINE"], series["MACD_SIGNAL"], series["MACD_HIST"] = m, s, hist
u, mid, lo_ = talib.BBANDS(C, 20, 2.0, 2.0, 0)
series["BB_UPPER"], series["BB_MIDDLE"], series["BB_LOWER"] = u, mid, lo_
series["ATR_14"] = talib.ATR(H, L, C, 14)
series["TRANGE"] = talib.TRANGE(H, L, C)
series["MAX_HIGH_14"] = talib.MAX(H, 14)
series["MIN_LOW_14"] = talib.MIN(L, 14)
series["MAX_CLOSE_14"] = talib.MAX(C, 14)
series["MIN_CLOSE_14"] = talib.MIN(C, 14)
series["STDDEV_20"] = talib.STDDEV(C, 20, 1.0)
# fastd/slowd period 1 so TA-Lib does not hold K back for the D line.
fk, _fd = talib.STOCHF(H, L, C, 14, 1, 0)
series["STOCHF_K_14"] = fk
sk, _sd = talib.STOCH(H, L, C, 14, 3, 1, 1, 0)
series["STOCH_SLOWK_EMA_14_3"] = sk
series["ROC_10"] = talib.ROC(C, 10)
series["OBV"] = talib.OBV(C, V)
series["MFI_14"] = talib.MFI(H, L, C, V, 14)
series["CCI_20"] = talib.CCI(H, L, C, 20)
series["PPO_EMA_12_26"] = talib.PPO(C, 12, 26, 1)
tp = talib.TYPPRICE(H, L, C)
series["KC_MIDDLE_20"] = talib.EMA(tp, 20)
series["ATR_20"] = talib.ATR(H, L, C, 20)
series["ATR_22"] = talib.ATR(H, L, C, 22)
series["MAX_HIGH_22"] = talib.MAX(H, 22)
series["MIN_LOW_22"] = talib.MIN(L, 22)
series["ADX_14"] = talib.ADX(H, L, C, 14)
series["DX_14"] = talib.DX(H, L, C, 14)
series["PLUS_DI_14"] = talib.PLUS_DI(H, L, C, 14)
series["MINUS_DI_14"] = talib.MINUS_DI(H, L, C, 14)
series["ADX_5"] = talib.ADX(H, L, C, 5)
series["DEMA_10"] = talib.DEMA(C, 10)
series["DEMA_3"] = talib.DEMA(C, 3)
series["WMA_10"] = talib.WMA(C, 10)
# Hull moving average (Alan Hull) from TA-Lib's WMA: WMA(2 WMA(n/2) - WMA(n), sqrt(n)), with
# n/2 and sqrt(n) rounded down. The wrapper starts each WMA at its input's first non-NaN.
series["HMA_16"] = talib.WMA(2.0 * talib.WMA(C, 8) - talib.WMA(C, 16), 4)
series["HMA_9"] = talib.WMA(2.0 * talib.WMA(C, 4) - talib.WMA(C, 9), 3)
# Not in TA-Lib: plain numpy definitions.
series["ER_10"] = er(C, 10)
series["MAD_20"] = mad(C, 20)


def lit(x):
    return "NAN" if np.isnan(x) else repr(float(x))


print("// @generated by tests/talib_reference/gen.py from TA-Lib", talib.__ta_version__.decode().split()[0], "- do not edit.")
print("// Inputs: a fixed-seed random walk. Outputs: TA-Lib with default compatibility")
print("// settings (NaN during each function's lookback). ER_10 and MAD_20 are not")
print("// TA-Lib functions; they come from straightforward numpy definitions.")
print("#![allow(dead_code, clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]")
print("const NAN: f64 = f64::NAN;")
print(f"pub const N: usize = {N};")
for name, arr in (("OPEN", o), ("HIGH", h), ("LOW", l), ("CLOSE", c), ("VOLUME", v)):
    print(f"pub const {name}: [f64; N] = [" + ", ".join(repr(float(x)) for x in arr) + "];")
for name, arr in series.items():
    print(f"pub const {name}: [f64; N] = [" + ", ".join(lit(x) for x in arr) + "];")
